def natural_sort_key(s):
    """
    Алгоритъм за 'естествено' сортиране (Natural Sort) на стрингове, съдържащи числа.
    Разделя подадения низ на текстови и числови компоненти чрез регулярни изрази (Regex),
    за да гарантира правилна подредба (напр. 'file2' да бъде преди 'file10').
    
    Параметри:
        s (str): Низът, който ще бъде сортиран.
        
    Връща:
        list: Масив от форматирани компоненти за лексикографско сравнение.
    """
    return [int(text) if text.isdigit() else text.lower() for text in re.split(r'(\d+)', s)]

def format_size(size_in_bytes):
    """
    Конвертира машинен размер на файл от байтове в четим човешки формат 
    (B, KB, MB, GB, TB) с точност до втория знак след десетичната запетая.
    
    Параметри:
        size_in_bytes (int/float): Размерът в байтове.
        
    Връща:
        str: Форматиран низ, съдържащ изчислената стойност и мерната единица.
    """
    for unit in ['B', 'KB', 'MB', 'GB', 'TB']:
        if size_in_bytes < 1024.0:
            return f"{size_in_bytes:.2f} {unit}"
        size_in_bytes /= 1024.0